def test_harness_rejects_served_model_or_exposed_tool_drift(tmp_path):
    phase = tmp_path / "attempt-1" / "phase-a"
    phase.mkdir(parents=True)
    allowed = {"get_task", "list_files", "read_code", "search_code", "find_symbol",
               "changed_files", "diff_file", "map_location", "submit_requirements"}
    meta = {
        "model": runner.MODEL, "effort": runner.EFFORT,
        "claude_code_version": runner.CLI_VERSION,
        "phase_budget_usd": 3.0, "max_budget_usd": 3.0, "timeout": 1200,
        "agent_environment": {"cwd": str(tmp_path / "isolated"), "model": runner.MODEL,
                              "tools": sorted(f"mcp__secreview__{x}" for x in allowed),
                              "memory_files": []},
    }
    (phase / "meta.json").write_text(json.dumps(meta))
    t = {"fixture": "fixture-secret", "revisions": {"revision_A": "a", "revision_B": "b"}}
    assert scoring.harness_problems(t, phase.parent) == []
    meta["agent_environment"]["model"] = "different-model"
    meta["agent_environment"]["tools"].append("Read")
    (phase / "meta.json").write_text(json.dumps(meta))
    problems = scoring.harness_problems(t, phase.parent)
    assert "a: served model drift" in problems
    assert "a: exposed tool surface drift" in problems


def test_missing_task_retains_role_and_truth_denominator(tmp_path, monkeypatch):
    truth = tmp_path / "fixture" / "requirement-truth.yaml"
    truth.parent.mkdir()
    truth.write_text(yaml.safe_dump({"items": [
        {"id": "e", "kind": "entry"}, {"id": "b", "kind": "behavior"},
    ]}))
    (truth.parent / "reference-result.json").write_text(json.dumps({
        "disposition": "PROVIDER_BLIND",
    }))
    monkeypatch.setattr(scoring.tasks, "task", lambda _: {
        "task_id": "task-x", "role": "real", "fixture": "f", "truth_path": str(truth),
    })
    monkeypatch.setattr(scoring.runner, "RUNS", tmp_path / "no-runs")
    row, problems = scoring.score_task("task-x")
    assert not problems and row["status"] == "MISSING" and row["role"] == "real"
    assert row["a"]["counts"]["entry"]["truth"] == 1
    assert row["a"]["counts"]["behavior"]["truth"] == 1
    assert row["failure_category"] == "RUN_MISSING"
