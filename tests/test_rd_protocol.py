def _git(tmp_path: Path) -> tuple[Path, str, str]:
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.name", "RD Pilot"], check=True)
    subprocess.run(["git", "-C", str(repo), "config", "user.email", "rd@example.invalid"], check=True)
    (repo / "p.go").write_text("package p\nfunc F(input string) {\n\tx := input\n\tsink(x)\n}\n")
    (repo / "SECURITY.md").write_text("hidden advisory\n")
    subprocess.run(["git", "-C", str(repo), "add", "."], check=True)
    subprocess.run(["git", "-C", str(repo), "commit", "-qm", "a"], check=True)
    a = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True,
                       text=True, check=True).stdout.strip()
    (repo / "p.go").write_text("package p\nfunc F(input string) {\n\tx := input\n\tif safe(x) {\n\t\tsink(x)\n\t}\n}\n")
    subprocess.run(["git", "-C", str(repo), "add", "p.go"], check=True)
    subprocess.run(["git", "-C", str(repo), "commit", "-qm", "b"], check=True)
    b = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True,
                       text=True, check=True).stdout.strip()
    return repo, a, b


def _anchor(line: int, expression: str) -> dict:
    return {"file": "p.go", "start_line": line, "end_line": line, "expression": expression}


def _requirements() -> dict:
    return {
        "entry": {r: {"state": "present", "anchor": _anchor(3, "x := input")}
                  for r in schema.REVISIONS},
        "behavior": {
            "revision_A": {"state": "present", "anchor": _anchor(4, "sink(x)")},
            "revision_B": {"state": "present", "anchor": _anchor(4, "if safe(x) {")},
        },
        "required_qualifiers": [],
        "rationale": "entry and deciding behavior",
    }


def _config(tmp_path: Path, phase: str, repo: Path, a: str, b: str) -> session.RDConfig:
    return session.RDConfig(
        session_id=f"test/{phase}", task_id="task-x", phase=phase, language="go",
        claim={"package": "p", "cwe": 400, "cwe_name": "Uncontrolled Resource Consumption"},
        repo=str(repo), revisions={"revision_A": a, "revision_B": b},
        out_dir=str(tmp_path / f"phase-{phase}"), artifact_dir=str(tmp_path / "artifacts"),
        analysis=({r: str(tmp_path / f"{r}.json.gz") for r in schema.REVISIONS}
                  if phase == "b" else {}),
    )


def _analysis(tmp_path: Path, a: str, b: str) -> None:
    # The test only needs one closed def_use relation instance.  Production rows are generated by
    # the frozen CodeQL queries; this synthetic unit test exercises the runtime over their format.
    for rev, commit in (("revision_A", a), ("revision_B", b)):
        doc = {"status": "ok", "commit": commit,
               "shapes": [["file", "p.go", 1, 1, 7], ["parameter", "p.go", 2, 8, 2],
                          ["definition", "p.go", 3, 2, 3], ["definition", "p.go", 4, 2, 4]],
               "rows": {"def_use": [["p.go", 2, 8, "p.go", 3, 2],
                                     ["p.go", 3, 2, "p.go", 4, 2]]}}
        (tmp_path / f"{rev}.json.gz").write_bytes(
            gzip.compress(json.dumps(doc).encode(), mtime=0))


def test_schema_rejects_coarse_or_malformed_shapes():
    with pytest.raises(schema.SchemaError, match="absent in both"):
        schema.slot({r: {"state": "absent", "context": _anchor(1, "package p")}
                     for r in schema.REVISIONS}, "entry")
    q = [{"kind": "UNSUPPORTED_REQUIREMENT_TYPE", "note": "x"}] * 3
    bad = _requirements() | {"required_qualifiers": q}
    with pytest.raises(schema.SchemaError, match="at most two"):
        schema.requirements(bad, lambda revision, anchor: None)


def test_source_surface_is_neutral_and_denies_advisories(tmp_path):
    repo, a, b = _git(tmp_path)
    source = SourceSurface(repo, {"revision_A": a, "revision_B": b})
    assert "revision_A" in source.read_code("revision_A", "p.go")["revision"]
    diff = source.diff_file("p.go")["diff"]
    assert "diff --git" not in diff and "index " not in diff and "---" not in diff
    assert source.list_files("revision_A")["files"] == ["p.go"]
    assert source.search_code("revision_A", "sink\\(x\\)")["hits"][0]["line"] == 4
    assert source.find_symbol("revision_A", "F")["hits"][0]["line"] == 2
    assert source.changed_files()["files"] == [{"status": "M", "revision_A_path": "p.go",
                                                   "revision_B_path": "p.go"}]
    assert source.map_location("revision_A", "p.go", 1)["to_revision"] == "revision_B"
    with pytest.raises(ToolInputError, match="not available"):
        source.read_code("revision_A", "SECURITY.md")


def test_a_b_c_surfaces_lock_and_return_closed_feedback(tmp_path):
    repo, a, b = _git(tmp_path)
    _analysis(tmp_path, a, b)

    phase_a = session.RDSession(_config(tmp_path, "a", repo, a, b))
    assert "check_hop" not in phase_a._tools
    locked_a = phase_a.call("submit_requirements", requirements=_requirements())
    assert locked_a["locked"] == "A"
    with pytest.raises(ToolInputError, match="locked"):
        phase_a.call("submit_requirements", requirements=_requirements())

    phase_b = session.RDSession(_config(tmp_path, "b", repo, a, b))
    assert "relations" in phase_b.call("get_task")
    hop = {"revision": "revision_A", "relation": "def_use",
           "from": _anchor(2, "input"), "to": _anchor(3, "x := input")}
    assert phase_b.call("check_hop", hop=hop) == {"feedback": "confirmed"}
    not_found = {**hop, "from": _anchor(3, "x := input")}
    assert phase_b.call("check_hop", hop=not_found) == {"feedback": "not confirmed"}
    unsupported = {**hop, "relation": "unsupported"}
    assert phase_b.call("check_hop", hop=unsupported) == {"feedback": "unable to confirm"}
    structurally_bad = {**hop, "to": _anchor(5, "}")}
    with pytest.raises(ToolInputError, match="must name"):
        phase_b.call("check_hop", hop=structurally_bad)
    unchecked = {**hop, "revision": "revision_B"}
    with pytest.raises(ToolInputError, match="byte-identically"):
        phase_b.call("submit_evidence", hops=[unchecked])
    locked_b = phase_b.call("submit_evidence", hops=[hop, unsupported], requirement_doubt=None)
    assert locked_b["locked"] == "B"

    phase_c = session.RDSession(_config(tmp_path, "c", repo, a, b))
    assert set(phase_c._tools) == {"get_task", "submit_conclusion"}
    with pytest.raises(ToolInputError, match="no such tool"):
        phase_c.call("read_code", revision="revision_A", path="p.go")
    locked_c = phase_c.call("submit_conclusion", conclusion={
        "revision_A": "SUPPORTED", "revision_B": "NOT_SUPPORTED", "rationale": "locked evidence"})
    assert locked_c["locked"] == "C"
    for name in ("a", "b", "c"):
        assert schema.verify_seal(json.loads((tmp_path / "artifacts" / f"{name}.json").read_text()))


def test_seal_detects_nested_tampering():
    artifact = schema.sealed({"schema": "x", "nested": {"value": 1}})
    artifact["nested"]["value"] = 2
    with pytest.raises(schema.SchemaError, match="mismatch"):
        schema.verify_seal(artifact)


def test_hop_check_limit_is_closed(tmp_path):
    repo, a, b = _git(tmp_path)
    _analysis(tmp_path, a, b)
    phase_a = session.RDSession(_config(tmp_path, "a", repo, a, b))
    phase_a.call("submit_requirements", requirements=_requirements())
    phase_b = session.RDSession(_config(tmp_path, "b", repo, a, b))
    hop = {"revision": "revision_A", "relation": "def_use",
           "from": _anchor(2, "input"), "to": _anchor(3, "x := input")}
    for _ in range(18):
        assert phase_b.call("check_hop", hop=hop)["feedback"] == "confirmed"
    with pytest.raises(ToolInputError, match="18-call"):
        phase_b.call("check_hop", hop=hop)


def test_graph_uses_only_recomputed_verified_edges(tmp_path):
    repo, a, b = _git(tmp_path)
    _analysis(tmp_path, a, b)
    docs = graph.load_analysis({r: str(tmp_path / f"{r}.json.gz") for r in schema.REVISIONS})
    scorer = graph.GraphScorer(language="go", repo=str(repo),
                               revisions={"revision_A": a, "revision_B": b}, analysis=docs)
    hop = {"revision": "revision_A", "relation": "def_use",
           "from": _anchor(3, "x := input"), "to": _anchor(4, "sink(x)")}
    requirements = _requirements()
    row = scorer.classify_revision(requirements, {"hops": [{"hop": hop, "state": "VERIFIED"}]},
                                   "revision_A")
    assert row["class"] == "FULL_CHAIN"
    tampered = scorer.classify_revision(requirements,
        {"hops": [{"hop": hop, "state": "UNVERIFIED"}]}, "revision_A")
    assert tampered["harness_mismatches"] and tampered["class"] == "FULL_CHAIN"

    monkeypatch = pytest.MonkeyPatch()
    monkeypatch.setattr(graph.verifiability, "verifiable_pair", lambda language, relation: False)
    try:
        unsupported = scorer.classify_revision(
            requirements, {"hops": [{"hop": hop, "state": "UNSUPPORTED"}]}, "revision_A")
    finally:
        monkeypatch.undo()
    assert unsupported["class"] == "NO_EVIDENCE" and not unsupported["harness_mismatches"]


def test_resumed_session_budget_caps_and_spend_are_cumulative(tmp_path, monkeypatch):
    monkeypatch.setattr(runner, "RUNS", tmp_path)
    assert runner.PHASE_BUDGET == {"a": 3.0, "b": 3.0, "c": 1.0}
    assert runner.SESSION_CAP == {"a": 3.0, "b": 6.0, "c": 7.0}
    attempt = tmp_path / "task-x" / "attempt-1"
    for phase, reported in (("a", 0.12), ("b", 0.28), ("c", 0.41)):
        phase_dir = attempt / f"phase-{phase}"
        phase_dir.mkdir(parents=True)
        (phase_dir / "agent.jsonl").write_text(json.dumps({
            "type": "result", "total_cost_usd": reported,
        }) + "\n")
    assert runner.observed_spend() == pytest.approx(0.41)

    # A second, result-less attempt reserves only the cumulative cap of its latest
    # started phase, rather than summing every resumed cap.
    phase_dir = tmp_path / "task-y" / "attempt-1" / "phase-b"
    phase_dir.mkdir(parents=True)
    (phase_dir / "agent.jsonl").write_text("")
    (phase_dir / "meta.json").write_text(json.dumps({"max_budget_usd": 6.0}))
    assert runner.observed_spend() == pytest.approx(6.41)


